// Throw 3 coins 6 times to get a hexagram
// Head=3 (yang), Tail=2 (yin)
export function throwCoins() {
  // Returns sum 6,7,8,9
  // 6=old yin (changing), 7=young yang, 8=young yin, 9=old yang (changing)
  const coins = [
    Math.random() < 0.5 ? 3 : 2,
    Math.random() < 0.5 ? 3 : 2,
    Math.random() < 0.5 ? 3 : 2,
  ];
  return coins.reduce((a, b) => a + b, 0);
}

export function generateHexagram() {
  const lines = [];
  for (let i = 0; i < 6; i++) {
    lines.push(throwCoins());
  }
  return hexagramFromLines(lines);
}

/** Build hexagram from pre-rolled lines (for interactive coin toss) */
export function hexagramFromLines(lines) {
  const binaryStr = lines.map(l => (l === 7 || l === 9) ? '1' : '0').join('');
  const num = (parseInt(binaryStr, 2) % 64) + 1;
  const hexagram = HEXAGRAMS.find(h => h.number === num) || HEXAGRAMS[0];
  return { hexagram, lines };
}

export function getLineSymbol(lineValue) {
  if (lineValue === 9) return '━━○━━'; // old yang (changing)
  if (lineValue === 7) return '━━━━━'; // young yang
  if (lineValue === 8) return '━━ ━━'; // young yin
  if (lineValue === 6) return '━━×━━'; // old yin (changing)
  return '━━━━━';
}
