export const ALL_CARDS = [...MAJOR_ARCANA, ...MINOR_CARDS];
export const SUITS_INFO = SUITS;

export function drawRandomCard(excludeIds = []) {
  const available = ALL_CARDS.filter(c => !excludeIds.includes(c.id));
  const card = available[Math.floor(Math.random() * available.length)];
  const isReversed = Math.random() < 0.3;
  return { ...card, isReversed };
}

export function drawMultipleCards(count, excludeIds = []) {
  const drawn = [];
  const exclude = [...excludeIds];
  for (let i = 0; i < count; i++) {
    const card = drawRandomCard(exclude);
    drawn.push(card);
    exclude.push(card.id);
  }
  return drawn;
}
